import type { KeyValueStore } from '../types';

/** An in-memory store for tests. `data` is exposed so tests can read or plant raw saved values. */
export function memStore(): KeyValueStore & { data: Map<string, string> } {
  const data = new Map<string, string>();
  return {
    data,
    get: async (k) => data.get(k) ?? null,
    set: async (k, v) => {
      data.set(k, v);
    },
    remove: async (k) => {
      data.delete(k);
    },
  };
}
